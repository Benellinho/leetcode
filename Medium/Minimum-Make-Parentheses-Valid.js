var minAddToMakeValid = function (s) {
    let erros = 0;
    let abre = 0;
    let fecha = 0;
    for (let i = 0; i < s.length; i++) {
        const element = s[i];
        if (element == "(") {
            abre++;
        }
        else if (element == ")") {
            fecha++;
        }
        if (fecha > abre) {
            erros++;
            abre++;
        }
    }
    if (abre > fecha) {
        erros = erros + (abre - fecha)
    }
    return erros;
};

